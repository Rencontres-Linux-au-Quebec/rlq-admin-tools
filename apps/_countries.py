def name(code, language="fr"):
    """Full name of the country in the language ("fr" or "en"; any other: English), or "" when the code is unknown."""
    pair = NAMES.get((code or "").strip().upper())
    if not pair:
        return ""
    return pair[0] if (language or "fr").lower().startswith("fr") else pair[1]


def label(code, language="fr"):
    """'CD (République démocratique du Congo)'; the code alone when it is unknown; "" for an empty code."""
    code = (code or "").strip().upper()
    full = name(code, language)
    return f"{code} ({full})" if full else code
